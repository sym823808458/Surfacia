"""Generate reference from the actual argparse builder without chemistry imports."""
import argparse
import ast
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def parser():
    source = ast.parse((ROOT / 'surfacia/cli.py').read_text(encoding='utf-8'))
    fn = next(n for n in source.body if isinstance(n, ast.FunctionDef) and n.name == 'build_parser')
    namespace = {'argparse': argparse}
    exec(compile(ast.Module(body=[fn], type_ignores=[]), 'surfacia/cli.py', 'exec'), namespace)
    return namespace['build_parser']()


def generate():
    result = parser()
    choices = next(a for a in result._actions if isinstance(a, argparse._SubParsersAction)).choices
    folder = ROOT / 'docs/source/_generated'
    folder.mkdir(parents=True, exist_ok=True)
    for name, item in [('surfacia', result), *choices.items()]:
        text = '.. Generated by tools/update_cli_reference.py; do not edit.\n\n.. code-block:: text\n\n'
        # argparse's wrapping/help layout changes across Python versions. Generate
        # stable text from the same action objects instead of format_help().
        lines = [item.prog, '', item.description or '']
        for group in item._action_groups:
            actions = [a for a in group._group_actions if a.help != argparse.SUPPRESS]
            if not actions:
                continue
            title = group.title
            if title in ('optional arguments', 'options'):
                title = 'options'
            lines += ['', title + ':']
            for action in actions:
                if isinstance(action, argparse._SubParsersAction):
                    lines += ['  commands: ' + ', '.join(action.choices)]
                    continue
                flag = ', '.join(action.option_strings) or action.dest
                if action.nargs != 0:
                    flag += ' ' + str(action.metavar or action.dest.upper())
                if action.required:
                    flag += ' (required)'
                lines += ['  ' + flag, '    ' + (action.help or '')]
                if action.choices is not None:
                    lines += ['    choices: ' + ', '.join(map(str, action.choices))]
        if item.epilog:
            lines += ['', textwrap.dedent(item.epilog).strip()]
        text += ''.join(('   ' + line.rstrip() if line.strip() else '') + '\n' for line in '\n'.join(lines).splitlines())
        (folder / (name + '.txt')).write_text(text.rstrip() + '\n', encoding='utf-8', newline='\n')
    print('Generated CLI references:', len(choices) + 1)


if __name__ == '__main__':
    generate()
